def _package_openai_zips(source_root: Path, zip_root: Path) -> int:
    skill_dirs = [
        path
        for path in sorted(source_root.iterdir())
        if path.is_dir() and not path.name.startswith(".")
    ]
    for skill_dir in skill_dirs:
        _validate_zip_source(skill_dir)
        _write_skill_zip(skill_dir, zip_root / f"{skill_dir.name}.zip")
    return len(skill_dirs)


def _validate_zip_source(skill_dir: Path) -> None:
    if not NAME_RE.fullmatch(skill_dir.name):
        raise BuildError(f"{_display_path(skill_dir)} must use a safe Skill name")
    symlinks = [path for path in sorted(skill_dir.rglob("*")) if path.is_symlink()]
    if symlinks:
        raise BuildError(f"{_display_path(symlinks[0])} must not be a symlink")
    files = [path for path in sorted(skill_dir.rglob("*")) if path.is_file()]
    root_skill = skill_dir / "SKILL.md"
    if not root_skill.is_file() or root_skill.is_symlink():
        raise BuildError(f"{_display_path(skill_dir)} is missing root SKILL.md")
    skill_files = [path for path in files if path.name == "SKILL.md"]
    if skill_files != [root_skill]:
        raise BuildError(f"{_display_path(skill_dir)} must contain exactly one SKILL.md")
    if len(files) > MAX_ZIP_FILES:
        raise BuildError(f"{_display_path(skill_dir)} exceeds zip file-count limit")
    total = 0
    for path in files:
        size = path.stat().st_size
        if size > MAX_ZIP_FILE_BYTES:
            raise BuildError(f"{_display_path(path)} exceeds zip file-size limit")
        total += size
    if total > MAX_ZIP_BYTES:
        raise BuildError(f"{_display_path(skill_dir)} exceeds zip size limit")


def _write_skill_zip(skill_dir: Path, zip_path: Path) -> None:
    with zipfile.ZipFile(zip_path, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for path in sorted(skill_dir.rglob("*")):
            if not path.is_file():
                continue
            relative = path.relative_to(skill_dir)
            info = zipfile.ZipInfo(f"{skill_dir.name}/{relative.as_posix()}", ZIP_TIMESTAMP)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            archive.writestr(info, path.read_bytes())


def _string_list(value: object) -> list[str]:
    if not isinstance(value, list):
        return []
    return [str(item).strip() for item in value if isinstance(item, str) and item.strip()]


