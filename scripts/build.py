class BuildError(Exception):
    """Raised when build inputs are malformed or unsafe."""


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Build hookless rd-skills Skills and Agent Profiles."
    )
    parser.add_argument("--profile", choices=PROFILES, default="recommended")
    args = parser.parse_args()

    try:
        result = build_profile(args.profile)
    except BuildError as exc:
        print(f"build: ERROR: {exc}", file=sys.stderr)
        return 1

    print(
        "build: built hookless profile "
        f"{args.profile} with {result['top_level_count']} standard Skill(s), "
        f"{result['compiled_layer3_reference_count']} compiled Layer 3 reference(s), "
        f"{result['agent_profile_count']} Agent Profile(s), and "
        f"{result['zip_count']} OpenAI API zip(s)."
    )
    return 0


def build_profile(profile: str) -> dict[str, Any]:
    if profile not in PROFILES:
        raise BuildError(f"unsupported profile: {profile}")

    # Nothing below this preflight may mutate a managed output. In particular,
    # the build also writes hosted-runtime zips, so their path chain must be
    # checked before the first profile reset rather than at packaging time.
    _preflight_static_paths(profile)
    registries = _load_registries()
    _preflight_registry_entries(registries)
    items = {
        layer: _load_items(layer, entries)
        for layer, entries in registries.items()
    }
    _validate_global_skill_names(items)
    profiles = _load_agent_profiles()
    enforcement = _load_host_enforcement()
    top_level = _top_level_items(profile, items)
    _preflight_build_plan(profile, top_level, items, profiles, enforcement)
    try:
        source_snapshot = authoritative_build_input_snapshot(ROOT)
    except (OSError, ValueError) as exc:
        raise BuildError(f"cannot snapshot authoritative build inputs: {exc}") from exc

    _clean_legacy_dist_artifacts()
    compiled_names = _build_skill_roots(
        profile,
        top_level,
        items,
        profiles,
        enforcement,
        source_snapshot,
    )
    _build_agent_profiles(profiles, enforcement)
    _reset_dir(OPENAI_ZIP_DIR / profile)
    _cleanup_legacy_zip_layout()
    zip_count = _package_openai_zips(
        UNIVERSAL_SKILLS_ROOT / profile,
        OPENAI_ZIP_DIR / profile,
    )
    return {
        "profile": profile,
        "top_level_count": len(top_level),
        "compiled_layer3_reference_count": len(compiled_names),
        "agent_profile_count": len(profiles),
        "zip_count": zip_count,
    }


def _preflight_static_paths(profile: str) -> None:
    """Validate every static input and managed output path before mutation."""
    source_directories = [SRC_DIR, REGISTRY_DIR, *LAYER_SOURCE_ROOTS.values()]
    source_files = [
        *(REGISTRY_DIR / spec[0] for spec in REGISTRY_SPECS.values()),
        PROFILE_SOURCE,
        HOST_ENFORCEMENT_SOURCE,
        CONTROL_PROMPT_SOURCE,
    ]

    for directory in source_directories:
        _require_within(directory, ROOT, "source directory")
        _reject_symlink_chain(directory, ROOT, "source directory")
        if not directory.is_dir() or directory.is_symlink():
            raise BuildError(f"{_display_path(directory)} must be a regular source directory")
        _reject_tree_symlinks(directory, "source tree")

    for file_path in source_files:
        _require_within(file_path, SRC_DIR, "source file")
        _reject_symlink_chain(file_path, ROOT, "source file")
        if not file_path.is_file() or file_path.is_symlink():
            raise BuildError(f"{_display_path(file_path)} must be a regular source file")

    prompt_bytes = CONTROL_PROMPT_SOURCE.read_bytes()
    try:
        prompt_text = prompt_bytes.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise BuildError("authoritative control prompt must be UTF-8") from exc
    projection_errors = prompt_projection_errors(
        prompt_text,
        CORE_CONTRACTS,
        document_bytes=prompt_bytes,
    )
    if projection_errors:
        raise BuildError(
            "authoritative control prompt projection is stale: "
            + "; ".join(projection_errors)
        )

    managed_outputs = _managed_output_paths(profile)
    _require_within(DIST_DIR, ROOT, "managed dist root")
    _reject_symlink_chain(DIST_DIR, ROOT, "managed dist root")
    if DIST_DIR.exists():
        if not DIST_DIR.is_dir() or DIST_DIR.is_symlink():
            raise BuildError(f"{_display_path(DIST_DIR)} must be a regular directory")
        _reject_tree_symlinks(DIST_DIR, "managed dist tree")
    for output in managed_outputs:
        _require_within(output, DIST_DIR, "managed output")
        _reject_symlink_chain(output, ROOT, "managed output")

    # Build inputs and managed output must never contain one another, even if a
    # test or embedding caller overrides the default roots.
    for source in [*source_directories, *source_files]:
        if _paths_overlap(source, DIST_DIR):
            raise BuildError(
                f"source/output overlap is forbidden: {_display_path(source)} and "
                f"{_display_path(DIST_DIR)}"
            )


def _managed_output_paths(profile: str) -> list[Path]:
    return [
        DIST_DIR,
        UNIVERSAL_SKILLS_ROOT / profile,
        *(root / profile for root in AGENT_SKILL_ROOTS),
        *(target for _platform, target in AGENT_PROFILE_OUTPUTS),
        OPENAI_ZIP_DIR,
        OPENAI_ZIP_DIR / profile,
    ]


def _preflight_registry_entries(
    registries: dict[str, list[dict[str, Any]]],
) -> None:
    for layer, entries in registries.items():
        source_root = LAYER_SOURCE_ROOTS[layer]
        for index, entry in enumerate(entries):
            context = f"{layer}[{index}]"
            name = _required_string(entry, "name", context)
            if not NAME_RE.fullmatch(name):
                raise BuildError(f"{context}: invalid Skill name {name!r}")
            raw_path = _required_string(entry, "path", context)
            if "\\" in raw_path:
                raise BuildError(f"{context}: path must use safe POSIX components")
            relative = PurePosixPath(raw_path)
            if relative.is_absolute() or any(
                part in {"", ".", ".."} for part in relative.parts
            ):
                raise BuildError(f"{context}: path must be a normalized repository path")

            expected = source_root / name
            try:
                expected_relative = expected.relative_to(ROOT).as_posix()
            except ValueError as exc:
                raise BuildError(f"{context}: configured layer root escapes the repository") from exc
            if relative.as_posix() != expected_relative:
                raise BuildError(
                    f"{context}: path must be the direct layer Skill root "
                    f"{expected_relative!r}"
                )

            path = ROOT.joinpath(*relative.parts)
            _require_within(path, source_root, f"{context} path")
            _reject_symlink_chain(path, ROOT, f"{context} path")
            if not path.is_dir() or path.is_symlink():
                raise BuildError(f"{context}: {_display_path(path)} must be a regular directory")
            _reject_tree_symlinks(path, f"{context} Skill tree")
            skill_file = path / "SKILL.md"
            if not skill_file.is_file() or skill_file.is_symlink():
                raise BuildError(f"{context}: {_display_path(skill_file)} must be a regular file")
            contracts = _item_reference_contracts(entry, context, name)
            for reference in contracts:
                reference_path = reference["path"]
                expected_type = reference_type_for_path(reference_path)
                if reference["type"] != expected_type:
                    raise BuildError(
                        f"{context}.reference_index: {reference_path!r} must use type "
                        f"{expected_type!r}, found {reference['type']!r}"
                    )
                target = path.joinpath(*PurePosixPath(reference_path).parts)
                _require_within(target, path, f"{context} Reference")
                _reject_symlink_chain(target, ROOT, f"{context} Reference")
                if not target.is_file() or target.is_symlink():
                    raise BuildError(
                        f"{context}: indexed Reference {_display_path(target)} must be a regular file"
                    )


def _validate_global_skill_names(items: dict[str, list[SkillItem]]) -> None:
    owners: dict[str, str] = {}
    for layer, layer_items in items.items():
        for item in layer_items:
            previous = owners.get(item.name)
            if previous is not None:
                raise BuildError(
                    f"Skill name {item.name!r} is duplicated across {previous} and {layer}"
                )
            owners[item.name] = layer


def _preflight_build_plan(
    profile: str,
    top_level: list[SkillItem],
    items: dict[str, list[SkillItem]],
    profiles: list[dict[str, Any]],
    enforcement: dict[str, Any],
) -> None:
    _validate_built_control_reference_reachability(top_level)
    layer3 = {item.name: item for item in [*items["foundation"], *items["domain"]]}
    domain_names = {item.name for item in items["domain"]}
    product_foundation_names = {
        item.name
        for item in items["foundation"]
        if item.registry.get("delivery_scope") == "product"
    }
    ownership_errors = foundation_ownership_errors(
        [item.registry for item in items["foundation"]],
        [item.registry for item in items["professional"]],
    )
    if ownership_errors:
        raise BuildError("; ".join(ownership_errors))
    for professional in items["professional"]:
        candidates = _layer3_names_for_professional(professional)
        if len(candidates) != len(_string_list(professional.registry.get("layer3_candidates"))):
            raise BuildError(f"{professional.name}: Layer 3 candidates must be unique")
        for name in candidates:
            if not NAME_RE.fullmatch(name):
                raise BuildError(f"{professional.name}: invalid Layer 3 candidate {name!r}")
            if name not in layer3:
                raise BuildError(f"{professional.name}: unknown Layer 3 candidate {name!r}")

    # Render every generated Skill into an unmanaged temporary directory and
    # run the same zip-source checks used after the build. This catches late
    # content, link-entrypoint, file-count, and size failures before dist reset.
    with tempfile.TemporaryDirectory(prefix="changeforge-build-preflight-") as raw:
        staging = Path(raw)
        for item in top_level:
            destination = staging / item.name
            _copy_skill_tree(item.path, destination)
            if item.layer == "control" and item.name == "engineering-control-plane":
                _write_compact_control_projection(destination, item)
                _copy_control_prompt(destination)
            else:
                _write_targeted_reference_contracts(destination, item)
            if item.layer == "professional":
                selected = _compiled_layer3_names(
                    profile,
                    item,
                    domain_names,
                    product_foundation_names,
                )
                if selected:
                    _write_layer3_references(destination, selected, layer3)
                _append_layer3_entrypoint(destination, profile)
                _validate_rendered_professional_body(destination / "SKILL.md")
            _validate_zip_source(destination)

    # Renderer failures are likewise configuration failures and must happen
    # before any existing Agent Profile directory is removed.
    for profile_entry in profiles:
        for platform, renderer in (
            ("codex", _render_codex_profile),
            ("claude", _render_claude_profile),
            ("copilot", _render_copilot_profile),
        ):
            rendered = renderer(profile_entry, enforcement)
            _validate_rendered_prompt_embedding(
                platform,
                profile_entry["name"],
                rendered,
            )
            _canonical_agent_profile_bytes(
                platform,
                profile_entry["name"],
                rendered,
            )


def _validate_built_control_reference_reachability(
    top_level: list[SkillItem],
) -> None:
    """Reject a registry projection that would hide a required built Reference."""

    controls = [
        item
        for item in top_level
        if item.layer == "control" and item.name == "engineering-control-plane"
    ]
    if len(controls) != 1:
        raise BuildError(
            "build must contain exactly one engineering-control-plane Skill"
        )
    contracts = _item_reference_contracts(
        controls[0].registry,
        controls[0].name,
        controls[0].name,
    )
    actual = [str(contract["path"]) for contract in contracts]
    expected = list(
        CORE_CONTRACTS["reference_contract"]["control_required_by"]
    )
    if actual != expected:
        raise BuildError(
            "control Reference registry must exactly expose the Core Model paths; "
            "otherwise a required Reference would be unreachable after build"
        )


def _validate_rendered_professional_body(skill_file: Path) -> None:
    """Reject a Professional root whose generated delivery exceeds the hard gate."""
    try:
        _metadata, _raw_frontmatter, body = parse_frontmatter(skill_file)
    except ValidationProblem as exc:
        raise BuildError(str(exc).replace(str(ROOT) + "/", "")) from exc
    line_count = len(body.splitlines())
    if line_count > MAX_RENDERED_PROFESSIONAL_BODY_LINES:
        raise BuildError(
            f"{_display_path(skill_file)}: rendered Professional SKILL.md body has "
            f"{line_count} lines; maximum is {MAX_RENDERED_PROFESSIONAL_BODY_LINES}"
        )


def _require_within(path: Path, root: Path, label: str) -> None:
    path_absolute = path.expanduser().absolute()
    root_absolute = root.expanduser().absolute()
    try:
        path_absolute.relative_to(root_absolute)
    except ValueError as exc:
        raise BuildError(
            f"{label} {_display_path(path)} must remain under {_display_path(root)}"
        ) from exc


def _reject_symlink_chain(path: Path, root: Path, label: str) -> None:
    path_absolute = path.expanduser().absolute()
    root_absolute = root.expanduser().absolute()
    try:
        relative = path_absolute.relative_to(root_absolute)
    except ValueError as exc:
        raise BuildError(f"{label} {_display_path(path)} escapes the repository") from exc
    cursor = root_absolute
    if cursor.is_symlink():
        raise BuildError(f"{label} {_display_path(cursor)} must not be a symlink")
    for part in relative.parts:
        cursor = cursor / part
        if cursor.is_symlink():
            raise BuildError(f"{label} {_display_path(cursor)} must not be a symlink")


def _reject_tree_symlinks(root: Path, label: str) -> None:
    for path in sorted(root.rglob("*")):
        if path.is_symlink():
            raise BuildError(f"{label} {_display_path(path)} must not be a symlink")


def _paths_overlap(left: Path, right: Path) -> bool:
    left_resolved = left.resolve(strict=False)
    right_resolved = right.resolve(strict=False)
    return (
        left_resolved == right_resolved
        or left_resolved in right_resolved.parents
        or right_resolved in left_resolved.parents
    )


def _display_path(path: Path) -> str:
    try:
        return path.expanduser().absolute().relative_to(ROOT.expanduser().absolute()).as_posix()
    except ValueError:
        return str(path)


def _load_registries() -> dict[str, list[dict[str, Any]]]:
    registries: dict[str, list[dict[str, Any]]] = {}
    for layer, (file_name, expected_kind, key) in REGISTRY_SPECS.items():
        path = REGISTRY_DIR / file_name
        if not path.is_file():
            raise BuildError(f"missing registry: {path.relative_to(ROOT)}")
        data = load_yaml_file(path)
        expected_schema_version = REGISTRY_SCHEMA_VERSIONS[layer]
        if (
            not isinstance(data, dict)
            or data.get("schema_version") != expected_schema_version
            or data.get("kind") != expected_kind
        ):
            raise BuildError(
                f"{path.relative_to(ROOT)} must use schema_version "
                f"{expected_schema_version} and kind {expected_kind}"
            )
        entries = data.get(key)
        if not isinstance(entries, list):
            raise BuildError(f"{path.relative_to(ROOT)}:{key} must be a list")
        normalized: list[dict[str, Any]] = []
        for index, entry in enumerate(entries):
            if not isinstance(entry, dict):
                raise BuildError(f"{file_name}:{key}[{index}] must be a mapping")
            required_fields = REQUIRED_REGISTRY_FIELDS
            if layer != "control":
                required_fields = (*required_fields, "required_expertise_tags")
            if layer == "foundation":
                required_fields = (*required_fields, "delivery_scope", "content_class")
            for field in required_fields:
                if field not in entry:
                    raise BuildError(f"{file_name}:{key}[{index}] missing {field}")
            if layer == "professional":
                _validate_role_contract_maps(entry, f"{file_name}:{key}[{index}]")
            if layer != "control":
                expertise_errors = required_expertise_tag_errors(
                    entry.get("required_expertise_tags"),
                    f"{file_name}:{key}[{index}]",
                    layer=layer,
                    skill_name=entry.get("name"),
                    foundation_group=entry.get("group"),
                )
                if expertise_errors:
                    raise BuildError("; ".join(expertise_errors))
            if layer == "foundation":
                context = f"{file_name}:{key}[{index}]"
                class_errors = [
                    *foundation_registry_field_errors(entry, context),
                    *foundation_content_class_errors(entry, context),
                ]
                if class_errors:
                    raise BuildError("; ".join(class_errors))
            normalized.append(entry)
        registries[layer] = normalized
    return registries


def _validate_role_contract_maps(entry: dict[str, Any], context: str) -> None:
    roles = _string_list(entry.get("role_support"))
    errors = [
        *role_contract_map_errors(entry.get("required_inputs_by_role"), roles, f"{context}.required_inputs_by_role"),
        *role_contract_map_errors(entry.get("output_contract_by_role"), roles, f"{context}.output_contract_by_role"),
    ]
    if errors:
        raise BuildError("; ".join(errors))


def _load_items(layer: str, entries: list[dict[str, Any]]) -> list[SkillItem]:
    items: list[SkillItem] = []
    seen: set[str] = set()
    for index, entry in enumerate(entries):
        name = _required_string(entry, "name", f"{layer}[{index}]")
        rel_path = _required_string(entry, "path", f"{layer}[{index}]")
        if name in seen:
            raise BuildError(f"duplicate {layer} Skill: {name}")
        seen.add(name)
        path = ROOT / rel_path
        skill_file = path / "SKILL.md"
        if not skill_file.is_file():
            raise BuildError(f"{rel_path} is missing SKILL.md")
        try:
            metadata, _raw, body = parse_frontmatter(skill_file)
        except ValidationProblem as exc:
            raise BuildError(str(exc).replace(str(ROOT) + "/", "")) from exc
        if metadata.get("name") != name:
            raise BuildError(f"{skill_file.relative_to(ROOT)} name does not match registry")
        description = metadata.get("description")
        if not isinstance(description, str) or not description.strip():
            raise BuildError(f"{skill_file.relative_to(ROOT)} is missing description")
        items.append(
            SkillItem(
                name=name,
                path=path,
                layer=layer,
                description=description.strip(),
                metadata=metadata,
                body=body,
                registry=dict(entry),
            )
        )
    return items


def _required_string(entry: dict[str, Any], field: str, context: str) -> str:
    value = entry.get(field)
    if not isinstance(value, str) or not value.strip():
        raise BuildError(f"{context}: {field} must be a non-empty string")
    return value.strip()


def _top_level_items(
    profile: str,
    items: dict[str, list[SkillItem]],
) -> list[SkillItem]:
    if profile == "recommended":
        return [*items["control"], *items["professional"]]
    if profile == "full":
        return [*items["control"], *items["professional"], *items["domain"]]
    if profile == "dev":
        return [
            *items["control"],
            *items["professional"],
            *items["foundation"],
            *items["domain"],
        ]
    raise BuildError(f"unsupported profile: {profile}")


def _build_skill_roots(
    profile: str,
    top_level: list[SkillItem],
    items: dict[str, list[SkillItem]],
    profiles: list[dict[str, Any]],
    enforcement: dict[str, Any],
    source_snapshot: dict[str, object],
) -> set[str]:
    layer3 = {
        item.name: item for item in [*items["foundation"], *items["domain"]]
    }
    domain_names = {item.name for item in items["domain"]}
    product_foundation_names = {
        item.name
        for item in items["foundation"]
        if item.registry.get("delivery_scope") == "product"
    }
    all_compiled: set[str] = set()
    for root in (UNIVERSAL_SKILLS_ROOT, *AGENT_SKILL_ROOTS):
        profile_root = root / profile
        _reset_dir(profile_root)
        compiled_by_skill: dict[str, list[str]] = {}
        for item in top_level:
            destination = profile_root / item.name
            _copy_skill_tree(item.path, destination)
            if item.layer == "control" and item.name == "engineering-control-plane":
                _write_compact_control_projection(destination, item)
                _copy_control_prompt(destination)
            else:
                _write_targeted_reference_contracts(destination, item)
            if item.layer == "professional":
                selected = _compiled_layer3_names(
                    profile,
                    item,
                    domain_names,
                    product_foundation_names,
                )
                compiled = (
                    _write_layer3_references(destination, selected, layer3)
                    if selected
                    else []
                )
                _append_layer3_entrypoint(destination, profile)
                compiled_by_skill[item.name] = compiled
                all_compiled.update(compiled)
        _write_build_manifest(
            profile_root,
            profile,
            top_level,
            items,
            compiled_by_skill,
            profiles,
            enforcement,
            source_snapshot,
        )
    return all_compiled


