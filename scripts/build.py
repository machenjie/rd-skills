def _write_compact_control_projection(destination: Path, item: SkillItem) -> None:
    """Emit the built-only Control router directly from Reference Contract v2."""

    skill_file = destination / "SKILL.md"
    try:
        _metadata, raw_frontmatter, _body = parse_frontmatter(skill_file)
    except ValidationProblem as exc:
        raise BuildError(str(exc)) from exc
    contracts = _item_reference_contracts(item.registry, item.name, item.name)
    rows: list[list[str]] = []
    for contract in contracts:
        path = str(contract["path"])
        label = PurePosixPath(path).stem.removesuffix("-template").split("-")[-1]
        rows.append(
            [
                f"[{label}]({path})",
                str(contract["type"]),
                str(contract["load_when"]),
                str(contract["do_not_load_when"]),
                ", ".join(contract["required_by"]),
                ", ".join(contract["required_output"]),
            ]
        )
    try:
        table = render_compact_markdown_table(
            TARGETED_REFERENCE_TABLE_COLUMNS,
            rows,
            f"{item.name}.reference_index",
        )
    except ValidationProblem as exc:
        raise BuildError(str(exc)) from exc
    table = "\n".join(
        re.sub(r"\s*\|\s*", "|", line) if line.startswith("|") else line
        for line in table.splitlines()
    )
    rendered = "\n".join(
        [
            "---",
            raw_frontmatter,
            "---",
            "",
            "# Engineering Control Plane",
            "",
            "Reference Contract v2; Prompt owns rules.",
            "No Profile: load [Prompt](references/main-control-agent.md).",
            "",
            "## Targeted References",
            "",
            *table.splitlines(),
            "",
        ]
    )
    skill_file.write_text(rendered, encoding="utf-8")


