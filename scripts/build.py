def _rewrite_layer3_links(body: str, name: str) -> str:
    body = re.sub(
        r"(?P<prefix>\]\()(?P<target>(?:\./)?references/[^)\s]+)(?P<suffix>\))",
        lambda match: (
            f"{match.group('prefix')}{name}/{match.group('target').removeprefix('./')}"
            f"{match.group('suffix')}"
        ),
        body,
    )
    body = re.sub(
        r"(?P<prefix>\]\()(?P<target>(?:\./)?examples/[^)\s]+)(?P<suffix>\))",
        lambda match: (
            f"{match.group('prefix')}{name}/{match.group('target').removeprefix('./')}"
            f"{match.group('suffix')}"
        ),
        body,
    )
    body = re.sub(
        r"`(?P<target>(?:\./)?(?:references|examples|assets)/[^`\s]+)`",
        lambda match: (
            f"`{name}/{match.group('target').removeprefix('./')}`"
        ),
        body,
    )
    return body


